package typescript

import (
	"os"
	"path/filepath"
	"strings"
)

const generatedHeader = "// Code generated by cmd/sdkgen from goswag; DO NOT EDIT.\n"

func (g *generator) writeTypeScript(name, content string) error {
	output := filepath.Join(g.output, "src")
	if err := os.MkdirAll(output, 0755); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(output, name), []byte(strings.TrimRight(content, "\n")+"\n"), 0644)
}
