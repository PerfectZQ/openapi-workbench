package golang

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"

	"github.com/PerfectZQ/openapi-workbench/contract"
)

func (g *generator) removeObsoleteServices(groups map[string][]contract.Method) error {
	output := g.output
	// Remove only this generator's obsolete service files when a route disappears.
	expected := map[string]bool{}
	for group := range groups {
		expected["api_"+strings.ToLower(group)+".gen.go"] = true
	}
	oldFiles, err := filepath.Glob(filepath.Join(output, "api_*.gen.go"))
	if err != nil {
		return err
	}
	for _, file := range oldFiles {
		if expected[filepath.Base(file)] {
			continue
		}
		content, err := os.ReadFile(file)
		if err != nil {
			return err
		}
		if !bytes.HasPrefix(content, []byte("// Code generated by cmd/sdkgen from goswag;")) {
			return fmt.Errorf("unowned generated file %s", file)
		}
		if err := os.Remove(file); err != nil {
			return err
		}
	}
	return nil
}

func (g *generator) writeGo(filename, imports, code string) error {
	prefix := "// Code generated by cmd/sdkgen from goswag; DO NOT EDIT.\npackage " + g.packageName + "\n"
	if imports != "" {
		prefix += "import (\n" + imports + "\n)\n"
	}
	data, err := format.Source([]byte(prefix + code))
	if err != nil {
		return fmt.Errorf("%s: %w", filename, err)
	}
	return os.WriteFile(filename, data, 0644)
}
